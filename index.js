const express = require("express");
const cors = require("cors");
const app = express();
app.use(cors());
app.use(express.json());
app.get("/", (req,res)=> res.send("Week 2 Express API is running"));
app.get("/api/hello", (req,res)=> res.json({message:"Hello from Express!"}));
app.get("/api/status", (req,res)=> res.json({status:"ok", uptime:process.uptime()}));
app.post("/api/echo", (req,res)=> res.json({youSent:req.body}));
app.listen(process.env.PORT || 3000, ()=> console.log("Running"));
